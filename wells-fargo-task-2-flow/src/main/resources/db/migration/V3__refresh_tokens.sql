-- ============================================================================
-- V3: server-side refresh tokens (RS256 access tokens + rotating refresh tokens).
-- Only the SHA-256 hash of each token is stored. Forward-only migration.
-- ============================================================================

create table refresh_tokens (
    id         bigint generated by default as identity primary key,
    version    bigint       not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    created_by varchar(100),
    updated_by varchar(100),
    user_id    bigint       not null,
    token_hash varchar(64)  not null,
    expires_at timestamp(6) not null,
    revoked    boolean      not null,
    constraint fk_refresh_token_user foreign key (user_id) references app_users (id)
);
create unique index idx_refresh_token_hash on refresh_tokens (token_hash);
