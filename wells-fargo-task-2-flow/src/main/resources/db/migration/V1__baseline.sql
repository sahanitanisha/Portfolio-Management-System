create table transactions (
    id                        bigint generated by default as identity primary key,
    version                   bigint                      not null,
    created_at                timestamp(6) not null,
    updated_at                timestamp(6) not null,
    created_by                varchar(100),
    updated_by                varchar(100),
    transaction_type          varchar(255)                not null,
    amount_value              numeric(19, 4)              not null,
    amount_currency           varchar(3)                  not null,
    balance_after_value       numeric(19, 4),
    balance_after_currency    varchar(3),
    description               varchar(500),
    executed_at               timestamp(6) not null,
    reference_number          varchar(64),
    status                    varchar(255)                not null,
    account_id                bigint                      not null,
    constraint uq_transaction_reference unique (reference_number),
    constraint fk_transaction_account foreign key (account_id) references accounts (id)
);
create index idx_tx_account on transactions (account_id);
create index idx_tx_executed_at on transactions (executed_at);

